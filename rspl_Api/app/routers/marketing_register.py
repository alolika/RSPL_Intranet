@router.get("/status", response_model=list[EnquiryStatusRow])
def get_enquiry_status_rows() -> list[EnquiryStatusRow]:
    with get_cursor() as cursor:
        cursor.execute(
            "SELECT AssignedToUserID, AssignedTo, AssignedToMobile, AssignedToEmail, COUNT(*) EnquiryCount, "
            "ROUND(SUM(StagePercent * 1.0) / COUNT(*), 2) ProgressPercent, MAX(LastActionDate) LastActionDate "
            "FROM vwWebEnquiry_Status WHERE StagePercent < 100 "
            "GROUP BY AssignedToUserID, AssignedTo, AssignedToMobile, AssignedToEmail ORDER BY LastActionDate ASC"
        )
        rows = rows_to_dicts(cursor)
    return [
        EnquiryStatusRow(
            assigned_to_user_id=r["AssignedToUserID"] or 0, assigned_to=r["AssignedTo"] or "",
            assigned_to_mobile=r["AssignedToMobile"] or "", assigned_to_email=r["AssignedToEmail"] or "",
            enquiry_count=r["EnquiryCount"] or 0, progress_percent=float(r["ProgressPercent"] or 0),
            last_action_date=r["LastActionDate"].isoformat() if r["LastActionDate"] else None,
        )
        for r in rows
    ]



@router.get("/rows", response_model=list[CustEnquiryRegisterRow])
def get_enquiry_register_rows(cust_id: int | None = None) -> list[CustEnquiryRegisterRow]:
    with get_cursor() as cursor:
        if cust_id is not None:
            cursor.execute(_ROWS_SELECT.format(top="", where="WHERE E.CustID = ?"), cust_id)
        else:
            cursor.execute(_ROWS_SELECT.format(top="TOP 500 ", where=""))
        rows = rows_to_dicts(cursor)
    return [_row_to_model(r) for r in rows]


@router.get("/lookup/contact-persons", response_model=list[dict])
def get_contact_person_lookup(search: str = "") -> list[dict]:
    """Mirrors CustEnquiryRegister.aspx.vb's ddlContact source (distinct
    CustomerMaster.Landmark values). Was an unbounded full list — on a table
    this size that's tens of thousands of distinct values shipped and
    rendered up front. Capped to TOP 100 + server-side search instead, same
    load-on-demand shape as every other customer/name picker in this app
    (e.g. this page's own Shop Name picker above)."""
    with get_cursor() as cursor:
        search = search.strip()
        if search:
            # Smart keyword search — see marketing_enquiry.get_customers_for_search.
            keywords = search.split()
            where_clause = " AND ".join(["Landmark LIKE ?"] * len(keywords))
            params = [f"%{kw}%" for kw in keywords]
            cursor.execute(
                "SELECT DISTINCT TOP 100 Landmark AS value, Landmark AS label FROM CustomerMaster "
                f"WHERE Landmark IS NOT NULL AND Landmark <> '' AND {where_clause} ORDER BY Landmark",
                *params,
            )
        else:
            cursor.execute(
                "SELECT DISTINCT TOP 100 Landmark AS value, Landmark AS label FROM CustomerMaster "
                "WHERE Landmark IS NOT NULL AND Landmark <> '' ORDER BY Landmark"
            )
        return rows_to_dicts(cursor)


_CUSTOMER_INFO_SELECT = (
    "SELECT TOP 1 CustID, DisplayName AS ShopName, "
    "ISNULL(FlatNo,'')+ISNULL(Floor,'')+ISNULL(BldgName,'')+ISNULL(Road,'')+','+ISNULL(Area,'')+','+ISNULL(City,'') AS Address, "
    "Landmark AS ContactPerson, MobileNo, PhNo, Email, GSTIN, ARN AS WebsiteName "
    "FROM CustomerMaster WHERE {where}"
)


def _row_to_customer_info(r: dict) -> CustomerRegisterInfo:
    return CustomerRegisterInfo(
        cust_id=r["CustID"], shop_name=r["ShopName"] or "", address=r["Address"] or "",
        contact_person=r["ContactPerson"] or "", mobile_no=r["MobileNo"] or "", tel_no=r["PhNo"] or "",
        email=r["Email"] or "", gstin=r["GSTIN"] or "", website_name=r["WebsiteName"] or "",
    )


@router.get("/customer-info/{cust_id}", response_model=CustomerRegisterInfo | None)
def get_customer_register_info(cust_id: int) -> CustomerRegisterInfo | None:
    """Direct by-ID lookup of the same Customer Information panel /search
    builds — used by pages that already have a resolved CustID (e.g.
    CustEnquiryAction, reached via a "Next Step" drill-down that already
    knows which customer) and just need to display who they're acting on,
    with no search-mode resolution step needed.
    """
    with get_cursor() as cursor:
        cursor.execute(_CUSTOMER_INFO_SELECT.format(where="CustID = ?"), cust_id)
        row = cursor.fetchone()
        if not row:
            return None
        r = dict(zip([c[0] for c in cursor.description], row))
    return _row_to_customer_info(r)


@router.get("/search", response_model=EnquiryRegisterSearchResult)
def search_enquiry_register(mode: str, value: str) -> EnquiryRegisterSearchResult:
    """Mirrors CustEnquiryRegister.aspx.vb's GetFilters()+btnshow_Click: resolve one
    CustID from the selected search mode, then load that customer's info panel and
    their enquiry rows (was `EXEC webproc_showenquiry @CustID, @AutoGenerated` in the
    source — @AutoGenerated is declared but never referenced in the proc body, so it
    has no effect on the result and is safely dropped here).
    """
    where_by_mode = {
        "shop_id": "CustID = ?",
        "cust_id": "CustID = ?",
        "contact_person": "Landmark = ?",
        "gst": "GSTIN = ?",
        "mobile": "(MobileNo = ? OR PhNo LIKE ?)",
    }
    if mode not in where_by_mode:
        return EnquiryRegisterSearchResult(customer_info=None, rows=[])

    select = _CUSTOMER_INFO_SELECT.format(where=where_by_mode[mode])
    with get_cursor() as cursor:
        if mode == "mobile":
            cursor.execute(select, value, f"%{value}%")
        else:
            cursor.execute(select, value)
        row = cursor.fetchone()
        if not row:
            return EnquiryRegisterSearchResult(customer_info=None, rows=[])
        r = dict(zip([c[0] for c in cursor.description], row))
        cust_id = r["CustID"]

        cursor.execute(_ROWS_SELECT.format(top="", where="WHERE E.CustID = ?"), cust_id)
        enquiry_rows = rows_to_dicts(cursor)

    return EnquiryRegisterSearchResult(customer_info=_row_to_customer_info(r), rows=[_row_to_model(er) for er in enquiry_rows])



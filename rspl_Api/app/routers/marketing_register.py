"""Mirrors Section_Marketing/CustEnquiryRegister.aspx.vb and
CustEnquiryStatus.aspx.vb ("Lead Pending Status").

CustEnquiryRegister's Angular rebuild previously diverged from the source: the
source only ever shows ONE customer's enquiry (search-driven — 5 radio-button
modes resolve to a single CustID, then `webproc_showenquiry` fills both a
"Customer Information" panel and the grid for that customer only), but the
Angular page had been simplified to a full scrollable register with no
customer search. `/search` below restores the original single-customer,
search-driven flow (reusing the `/rows` query body with a CustID filter
instead of calling `webproc_showenquiry` directly — its full `E.*` column set
isn't confirmed 1:1, whereas this SELECT already is). `/rows` itself is kept
(now with an optional `cust_id` filter) since nothing about removing the
all-customers view was requested. IntroducedBy/ReferredBy/Campaign/
CurrentSoftware/CaseType are only partially populated from what Web_Enquiry
actually stores (best-effort, not all fields have a confirmed real source
column).

The WhatsApp "send" button calls `Proc_DripSendWhatsApp`, which sends a
real outbound WhatsApp message — same category of hazard as Section_General's
leave-workflow email/WhatsApp calls (see [[feedback_report_engine_simplification]]-
adjacent memory). Stubbed here (no actual send) rather than re-asking, per the
established default for this category of side effect.
"""

from fastapi import APIRouter
from pydantic import BaseModel

from app.db import get_cursor, rows_to_dicts

router = APIRouter(prefix="/marketing/register", tags=["marketing-register"])

_ROWS_SELECT = """
    SELECT {top}E.CustID, E.EnquiryDate, ISNULL(S.StagePercent, 0) AS StagePercent,
           ISNULL(UM.Name, '') AS ReceivedByName, E.Narration, ISNULL(S.SegmentName, '') AS SegmentName,
           ISNULL(NB.MasterValue, '') AS BusinessNatureName, ISNULL(ST.MasterValue, '') AS SourceTypeName,
           E.SourceNarration, ISNULL(IB.Name, '') AS IntroducedByName, ISNULL(RC.DisplayName, '') AS ReferredByName,
           ISNULL(CM.MasterValue, '') AS CampaignName, E.HardwarePatner,
           CASE WHEN E.AutoGenerated = 1 THEN 'Auto' ELSE 'New' END AS CaseType
    FROM Web_Enquiry E
    LEFT JOIN vwWebEnquiry_Status S ON S.CustID = E.CustID
    LEFT JOIN UserMaster UM ON UM.UserID = E.ReceivedBy
    LEFT JOIN Web_LittleMaster NB ON NB.ID = E.NatureOfBusiness AND NB.MasterName = 'BusinessNature'
    LEFT JOIN Web_LittleMaster ST ON ST.ID = E.Sourcetype AND ST.MasterName = 'EnquirySourceType'
    LEFT JOIN UserMaster IB ON IB.UserID = E.IntroducedBy
    LEFT JOIN CustomerMaster RC ON RC.CustID = E.ReferredCustID
    LEFT JOIN Web_LittleMaster CM ON CM.ID = E.Campaign AND CM.MasterName = 'Campaign'
    {where}
    ORDER BY E.EnquiryDate DESC
"""


